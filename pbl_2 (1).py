    def detect_waste(self, image):
        """
        Detect waste in the image using computer vision.
        Returns the waste type and bounding box coordinates.
        """
        # Convert to HSV for easier color segmentation
        hsv = cv2.cvtColor(image, cv2.COLOR_BGR2HSV)

        detected_objects = []

        # Detect objects of each waste category based on color
        for category, info in self.waste_categories.items():
            lower, upper = info['color_range']
            mask = cv2.inRange(hsv, np.array(lower), np.array(upper))

            # For plastic, add additional color ranges
            if category == 'plastic':
                for add_range in self.additional_plastic_ranges:
                    add_lower, add_upper = add_range
                    add_mask = cv2.inRange(hsv, np.array(add_lower), np.array(add_upper))
                    mask = cv2.bitwise_or(mask, add_mask)

            # Apply morphological operations to reduce noise
            kernel = np.ones((5, 5), np.uint8)
            mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, kernel)
            mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, kernel)

            # Find contours in the mask
            contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

            # Process each contour as a potential waste object
            for contour in contours:
                if cv2.contourArea(contour) > 500:  # Filter small contours
                    x, y, w, h = cv2.boundingRect(contour)
                    confidence = self._calculate_confidence(hsv[y:y+h, x:x+w], lower, upper)

                    # For plastic, check additional confidence with other ranges
                    if category == 'plastic':
                        for add_range in self.additional_plastic_ranges:
                            add_lower, add_upper = add_range
                            add_confidence = self._calculate_confidence(hsv[y:y+h, x:x+w], add_lower, add_upper)
                            confidence = max(confidence, add_confidence)

                    detected_objects.append({
                        'category': category,
                        'label': info['label'],
                        'bbox': (x, y, w, h),
                        'confidence': confidence
                    })

        # Sort by confidence (highest first)
        detected_objects.sort(key=lambda x: x['confidence'], reverse=True)

        return detected_objects

    def _calculate_confidence(self, roi_hsv, lower, upper):
        """Calculate confidence score based on how well the ROI matches the color range"""
        # Simple heuristic: percentage of pixels within the color range
        mask = cv2.inRange(roi_hsv, np.array(lower), np.array(upper))
        return np.count_nonzero(mask) / (roi_hsv.shape[0] * roi_hsv.shape[1] + 1e-10)  # Avoid div by zero

    def classify_waste_by_features(self, image, bbox):
        """
        Use advanced features to classify waste.
        In a real implementation, this would use a proper ML model.
        """
        x, y, w, h = bbox
        roi = image[y:y+h, x:x+w]

        # Extract features
        hsv_roi = cv2.cvtColor(roi, cv2.COLOR_BGR2HSV)
        avg_color = np.mean(hsv_roi, axis=(0, 1))

        # Check texture features (simple variance)
        gray_roi = cv2.cvtColor(roi, cv2.COLOR_BGR2GRAY)
        texture_variance = np.var(gray_roi)

        best_match = None
        best_score = -1

        # Create feature vector [hue, saturation, value, texture_variance]
        features = np.append(avg_color, texture_variance)

        for category, info in self.waste_categories.items():
            lower, upper = info['color_range']

            # Calculate base score from color distance
            h_dist = min(abs(avg_color[0] - ((lower[0] + upper[0]) / 2)),
                         180 - abs(avg_color[0] - ((lower[0] + upper[0]) / 2))) / 180.0
            s_dist = abs(avg_color[1] - ((lower[1] + upper[1]) / 2)) / 255.0
            v_dist = abs(avg_color[2] - ((lower[2] + upper[2]) / 2)) / 255.0

            # Combine distances with weights
            color_score = 1.0 - (0.6 * h_dist + 0.2 * s_dist + 0.2 * v_dist)

            # Apply texture-based rules
            # Plastics often have smoother texture (lower variance)
            if category == 'plastic' and texture_variance < 1000:
                color_score += 0.2

            # Paper often has medium texture
            if category == 'paper' and 1000 <= texture_variance <= 3000:
                color_score += 0.2

            # Additional check for plastic's additional ranges
            if category == 'plastic':
                for add_range in self.additional_plastic_ranges:
                    add_lower, add_upper = add_range
                    add_h_dist = min(abs(avg_color[0] - ((add_lower[0] + add_upper[0]) / 2)),
                                     180 - abs(avg_color[0] - ((add_lower[0] + add_upper[0]) / 2))) / 180.0
                    add_score = 1.0 - add_h_dist
                    color_score = max(color_score, add_score)

            if color_score > best_score:
                best_score = color_score
                best_match = category

        return best_match, best_score

    def visualize_detection(self, image, detections):
        """Visualize the detected waste objects with bounding boxes and labels"""
        output = image.copy()

        # Draw bounding boxes and labels
        for detection in detections:
            category = detection['category']
            label = detection['label']
            x, y, w, h = detection['bbox']
            confidence = detection['confidence']

            # Get color for this category
            if category == 'plastic':
                color = (0, 0, 255)  # Red for plastic
            elif category == 'paper':
                color = (255, 255, 0)  # Cyan for paper
            elif category == 'metal':
                color = (0, 255, 0)  # Green for metal
            elif category == 'glass':
                color = (255, 0, 0)  # Blue for glass
            else:  # organic
                color = (0, 255, 255)  # Yellow for organic

            # Draw bounding box
            cv2.rectangle(output, (x, y), (x+w, y+h), color, 2)

            # Draw label with confidence
            label_text = f"{label}: {confidence:.2f}"
            cv2.putText(output, label_text, (x, y-10), cv2.FONT_HERSHEY_SIMPLEX,
                        0.5, color, 2)

        return output

    def sort_waste(self, image):
        """Main function to detect and sort waste in an image"""
        start_time = time.time()

        # Step 1: Detect waste objects in the image
        detections = self.detect_waste(image)

        # If no waste detected
        if not detections:
            print("No waste detected in the image.")
            return image, []

        # Step 2: Process each detected object
        for detection in detections:
            category = detection['category']
            bbox = detection['bbox']

            # Refine classification with more advanced features
            refined_category, confidence = self.classify_waste_by_features(image, bbox)
            detection['category'] = refined_category
            detection['label'] = self.waste_categories[refined_category]['label']
            detection['confidence'] = confidence

            # Update statistics
            self.stats[refined_category] += 1
            self.total_processed += 1

            # Log the detection
            self._log_detection(refined_category, confidence)

            # Simulate robotic arm movement to sort the waste
            x, y, w, h = bbox
            target_x, target_y = x + w//2, y + h//2  # Target center of object
            self.robot_arm.move_to(target_x, target_y)
            self.robot_arm.pickup()
            self.robot_arm.move_to_bin(refined_category)
            self.robot_arm.release()

        # Step 3: Visualize results
        output_image = self.visualize_detection(image, detections)

        # Calculate processing time
        processing_time = time.time() - start_time
        print(f"Processing completed in {processing_time:.2f} seconds")

        return output_image, detections

