class VirtualRobotArm:
    """Simulate a robotic arm for waste sorting"""
    def __init__(self):
        self.x = 0
        self.y = 0
        self.holding = False
        self.bin_positions = {
            'plastic': (100, 500),
            'paper': (300, 500),
            'metal': (500, 500),
            'glass': (700, 500),
            'organic': (900, 500)
        }
        print("Virtual robot arm initialized.")

    def move_to(self, x, y):
        """Move the arm to the specified coordinates"""
        print(f"Moving arm to position ({x}, {y})")
        # Simulate movement time
        time.sleep(0.1)  # Reduced for faster simulation
        self.x, self.y = x, y

    def pickup(self):
        """Simulate picking up an item"""
        if not self.holding:
            print(f"Picking up item at position ({self.x}, {self.y})")
            self.holding = True
            # Simulate pickup time
            time.sleep(0.1)  # Reduced for faster simulation
        else:
            print("Cannot pick up: already holding an item")

    def move_to_bin(self, waste_type):
        """Move to the bin for the specified waste type"""
        if waste_type in self.bin_positions:
            bin_x, bin_y = self.bin_positions[waste_type]
            print(f"Moving to {waste_type} bin at position ({bin_x}, {bin_y})")
            # Simulate movement time
            time.sleep(0.1)  # Reduced for faster simulation
            self.x, self.y = bin_x, bin_y
        else:
            print(f"Unknown bin type: {waste_type}")

    def release(self):
        """Release the held item"""
        if self.holding:
            print(f"Releasing item at position ({self.x}, {self.y})")
            self.holding = False
            # Simulate release time
            time.sleep(0.1)  # Reduced for faster simulation
        else:
            print("Nothing to release: not holding an item")


